// Sugerir Agendamento: quadro com seletor de semanas confere a semana em que a sessão está no Planner.
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
(async () => {
  const src = fs.readFileSync(path.join(__dirname, 'page.html'), 'utf8');
  const i = src.indexOf('"use strict";');
  const evPage = path.join(__dirname, 'page_sgw.html');
  fs.writeFileSync(evPage, src.slice(0, i + 13) + '\nwindow.__ev = function(x){ return eval(x); };\n' + src.slice(i + 13));
  const browser = await chromium.launch(require('./launch-opts'));
  const page = await browser.newPage({ viewport: { width: 1400, height: 900 } });
  const errors = []; page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('file://' + evPage);
  await page.waitForSelector('#gridHost .book');
  const ev = (c) => page.evaluate((x) => window.__ev(x), c);
  let fails = 0;
  const check = (l, ok, x) => { console.log(l, !!ok, x === undefined ? '' : x); if (!ok) fails++; };
  await ev(`(async function(){
    var db = await window.claude.use('db');
    await db.doc('config/specialties').set({list: [{id: 'fono', name: 'Fonoaudiologia', sigla: 'FN'}]});
    await db.doc('config/professionals').set({list: [{id: 'f1', nome: 'Fono Um', name: 'Fono Um', specialtyId: 'fono'}]});
    await db.doc('config/rooms').set({list: [{id: 'rA', name: 'Fonoaudiologia', aba: false, color: 'teal', therapists: [{id: 'a1', name: 'Fono Um', professionalId: 'f1'}]}]});
    await db.doc('patients/all').set({list: [{id: 'pa', nome: 'Paciente A', idade: 8}]});
    var ids = []; ['seg','ter','qua','qui','sex'].forEach(function(d){ for (var w = 1; w <= 4; w++) ids.push(d + '-' + w); });
    for (var k = 0; k < ids.length; k++) await db.doc('schedule/' + ids[k]).set({bookings: {}});
    await db.doc('schedule/seg-1').set({bookings: {'07:20|rA|a1': {patient: 'Paciente A', note: '', service: 'sessao'}}});
    await db.doc('schedule/seg-2').set({bookings: {'07:20|rA|a1': {patient: 'Paciente A', note: '', service: 'sessao'}}});
  })()`);
  await page.waitForTimeout(700);
  await ev(`(function(){ state.treatments = [{id: 'ta', patientId: 'pa', inicio: '2026-01-01', status: 'ativo', tipo: 'novo', vencPor: 'sem', specHours: [{id: 'lf', specId: 'fono', hours: 2, service: 'sessao', semanas: '1,3'}]}]; rebuildPatients(); })()`);
  await page.click('#plToolsBtn'); await page.waitForTimeout(150);
  await page.$eval('#plSugBtn', (b) => b.click());
  await page.waitForSelector('#ovPlSg'); await page.waitForTimeout(400);
  await page.$eval('#sgPat', (s) => { s.value = 'pa'; s.dispatchEvent(new Event('change', { bubbles: true })); });
  await page.waitForSelector('[data-sg-fx]', {timeout: 4000}).catch(() => {});
  const fx = await page.$$eval('[data-sg-fx]', (a) => a.map((c) => c.parentElement.textContent.trim()));
  check('Sessão na 2ª semana (quadro só 1ª e 3ª) é levada para a 3ª?', fx.some((t) => /Semana fora do quadro/.test(t) && /2ª semana/.test(t) && /3ª semana/.test(t)), JSON.stringify(fx));
  const body = await page.innerText('#ovPlSg');
  check('Não sugere sessão nova (já tem as 2)?', !/\[data-sg-on\]/.test(body) && (await page.$$('[data-sg-on]')).length === 0);
  await page.click('#sgApply');
  await page.waitForSelector('.confirm-overlay button.primary, .confirm-overlay .btn:not(.ghost)');
  await page.click('.confirm-overlay button.primary, .confirm-overlay .btn:not(.ghost)');
  await page.waitForTimeout(900);
  const st = await ev(`(function(){ var o = {}; Object.keys(window.__STORE__).forEach(function(p){ if (p.indexOf('schedule/') !== 0) return; var bk = (window.__STORE__[p] || {}).bookings || {}; Object.keys(bk).forEach(function(k){ if (bk[k] && bk[k].patient) { var w = p.split('-')[1]; o["w" + w] = (o["w" + w] || 0) + 1; } }); }); return JSON.stringify(o); })()`);
  const o = JSON.parse(st);
  check('Aplicado: saiu da 2ª e entrou na 3ª semana?', !o.w2 && o.w1 === 1 && o.w3 === 1, st);
  console.log('no JS errors?', errors.length === 0, errors.slice(0, 3));
  await browser.close(); fs.unlinkSync(evPage);
  process.exit(fails || errors.length ? 1 : 0);
})();
