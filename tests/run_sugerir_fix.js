// Sugerir Agendamento: correções nas sessões já marcadas (troca de especialidade e equilíbrio entre as semanas).
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
(async () => {
  const src = fs.readFileSync(path.join(__dirname, 'page.html'), 'utf8');
  const i = src.indexOf('"use strict";');
  const evPage = path.join(__dirname, 'page_sgf.html');
  fs.writeFileSync(evPage, src.slice(0, i + 13) + '\nwindow.__ev = function(x){ return eval(x); };\n' + src.slice(i + 13));
  const browser = await chromium.launch(require('./launch-opts'));
  const page = await browser.newPage({ viewport: { width: 1400, height: 900 } });
  const errors = []; page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('file://' + evPage);
  await page.waitForSelector('#gridHost .book');
  const ev = (c) => page.evaluate((x) => window.__ev(x), c);
  let fails = 0;
  const check = (l, ok, x) => { console.log(l, !!ok, x === undefined ? '' : x); if (!ok) fails++; };
  await ev(`(async function(){
    var db = await window.claude.use('db');
    await db.doc('config/specialties').set({list: [{id: 'fono', name: 'Fonoaudiologia', sigla: 'FN'}, {id: 'nutri', name: 'Nutrição', sigla: 'NU'}]});
    await db.doc('config/professionals').set({list: [{id: 'f1', nome: 'Fono Um', name: 'Fono Um', specialtyId: 'fono'}, {id: 'n1', nome: 'Nutri Um', name: 'Nutri Um', specialtyId: 'nutri'}]});
    await db.doc('config/rooms').set({list: [{id: 'rA', name: 'Fonoaudiologia', aba: false, color: 'teal', therapists: [{id: 'a1', name: 'Fono Um', professionalId: 'f1'}]}, {id: 'rB', name: 'Nutrição', aba: false, color: 'blue', therapists: [{id: 'b1', name: 'Nutri Um', professionalId: 'n1'}]}]});
    await db.doc('patients/all').set({list: [{id: 'pa', nome: 'Paciente A', idade: 8}]});
    var ids = []; ['seg','ter','qua','qui','sex'].forEach(function(d){ for (var w = 1; w <= 4; w++) ids.push(d + '-' + w); });
    for (var k = 0; k < ids.length; k++) await db.doc('schedule/' + ids[k]).set({bookings: {}});
    var r = function(){ return {patient: 'Paciente A', note: '', service: 'sessao'}; };
    await db.doc('schedule/seg-1').set({bookings: {'07:20|rB|b1': r(), '08:00|rB|b1': r(), '08:40|rB|b1': r()}});
    await db.doc('schedule/qua-1').set({bookings: {'07:20|rB|b1': r()}});
    await db.doc('schedule/qua-2').set({bookings: {'07:20|rB|b1': r()}});
  })()`);
  await page.waitForTimeout(700);
  await ev(`(function(){ state.treatments = [{id: 'ta', patientId: 'pa', inicio: '2026-01-01', status: 'ativo', tipo: 'novo', vencPor: 'sem', specHours: [{id: 'ln', specId: 'nutri', hours: 4, service: 'sessao'}, {id: 'lf', specId: 'fono', hours: 2, service: 'sessao'}]}]; rebuildPatients(); })()`);
  await page.click('#plToolsBtn'); await page.waitForTimeout(150);
  await page.$eval('#plSugBtn', (b) => b.click());
  await page.waitForSelector('#ovPlSg'); await page.waitForTimeout(400);
  await page.$eval('#sgPat', (s) => { s.value = 'pa'; s.dispatchEvent(new Event('change', { bubbles: true })); });
  await page.waitForSelector('[data-sg-fx]');
  const fx = await page.$$eval('[data-sg-fx]', (a) => a.map((c) => c.parentElement.textContent.trim()));
  check('Oferece trocar uma Nutrição a mais por Fonoaudiologia?', fx.some((t) => /Trocar a especialidade/.test(t) && /Nutrição/.test(t) && /Fonoaudiologia/.test(t)), JSON.stringify(fx));
  check('Oferece equilibrar as semanas?', fx.some((t) => /Equilibrar as semanas/.test(t)), JSON.stringify(fx));
  check('Correções vêm marcadas?', await page.$$eval('[data-sg-fx]', (a) => a.every((c) => c.checked)));
  await page.click('#sgApply');
  await page.waitForSelector('.confirm-overlay button.primary, .confirm-overlay .btn:not(.ghost)');
  await page.click('.confirm-overlay button.primary, .confirm-overlay .btn:not(.ghost)');
  await page.waitForTimeout(900);
  const cnt = await ev(`(function(){ var n = {nutri: 0, fono: 0, byWeek: {}}; Object.keys(window.__STORE__).forEach(function(p){ if (p.indexOf('schedule/') !== 0) return; var w = p.split('-')[1]; var bk = (window.__STORE__[p] || {}).bookings || {}; Object.keys(bk).forEach(function(k){ if (!bk[k].patient) return; if (k.indexOf('|rB|') > 0){ n.nutri++; n.byWeek[w] = (n.byWeek[w] || 0) + 1; } else if (k.indexOf('|rA|') > 0) n.fono++; }); }); return JSON.stringify(n); })()`);
  const c = JSON.parse(cnt);
  check('Nutrição ficou com 4 e Fono recebeu a sessão trocada?', c.nutri === 4 && c.fono >= 1, cnt);
  const spread = Object.values(c.byWeek);
  check('Nutrição repartida (nenhuma semana com 3 ou mais)?', Math.max.apply(null, spread) <= 2, cnt);
  check('no JS errors?', errors.length === 0, JSON.stringify(errors));
  fs.unlinkSync(evPage);
  await browser.close();
  process.exit(fails ? 1 : 0);
})();
