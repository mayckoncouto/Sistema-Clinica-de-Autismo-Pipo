// Planner ▾ → Resumo do Planner: três visões (mapa de calor, por profissional, por paciente), filtros e quadro de detalhes.
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
(async () => {
  const src = fs.readFileSync(path.join(__dirname, 'page.html'), 'utf8');
  const i = src.indexOf('"use strict";');
  const evPage = path.join(__dirname, 'page_rsp.html');
  fs.writeFileSync(evPage, src.slice(0, i + 13) + '\nwindow.__ev = function(x){ return eval(x); };\n' + src.slice(i + 13));
  const browser = await chromium.launch(require('./launch-opts'));
  const page = await browser.newPage({ viewport: { width: 1400, height: 900 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('file://' + evPage);
  await page.waitForTimeout(800);
  const ev = (c) => page.evaluate((x) => window.__ev(x), c);
  let fails = 0;
  const check = (label, ok, extra) => { console.log(label, ok, extra === undefined ? '' : extra); if (!ok) fails++; };
  const setup = await ev(`(function(){
    var rooms = state.rooms.filter(function(r){ return !r.group && r.therapists && r.therapists.length; });
    var r1 = rooms[0], t1 = r1.therapists[0];
    var pats = state.patients.slice(0, 2);
    state.reportDocs = {"seg-1": {bookings: {}}, "qua-3": {bookings: {}}};
    state.reportDocs["seg-1"].bookings["08:00|" + r1.id + "|" + t1.id] = {patient: pats[0].nome, service: "sessao"};
    state.reportDocs["seg-1"].bookings["09:20|" + r1.id + "|" + t1.id] = {patient: pats[0].nome, service: "sessao"};
    state.reportDocs["qua-3"].bookings["09:20|" + r1.id + "|" + t1.id] = {patient: pats[1].nome, service: "sessao"};
    state.reportDocs["qua-3"].bookings["10:00|" + r1.id + "|" + t1.id] = {patient: "", blocked: true};
    return {n1: pats[0].nome};
  })()`);
  await ev(`document.querySelector('#mainTabs button[data-tab="resumoplanner"]').click()`);
  await page.waitForTimeout(500);
  check('abre a tela', (await ev(`state.tab`)) === 'resumoplanner');
  check('título', /Resumo do Planner/.test(await page.textContent('#tab-resumoplanner .cad-title')));
  check('cartão Atendimentos = 3', /3/.test(await page.textContent('#rspSum .fl-card:nth-child(3) b')));
  check('mapa de calor com 2 pacientes', (await page.$$eval('#rspMain .rsp-tbl tbody tr:not(.rsp-tot)', (t) => t.length)) === 2);
  check('célula do paciente 1 com 2', (await page.$$eval('#rspMain td[data-rsp-pc]', (t) => t.map((x) => x.textContent))).includes('2'));
  await page.click('#rspMain td[data-rsp-pc]');
  check('abre o quadro de detalhes', await page.isVisible('#rspDrawer') && (await page.$$eval('#rspDrawer li', (t) => t.length)) >= 1);
  await page.click('#rspSeg [data-rsp-v="prof"]');
  check('visão por profissional', (await page.$$eval('#rspMain .rsp-pc', (t) => t.length)) === 1);
  await page.click('#rspSeg [data-rsp-v="pac"]');
  check('visão por paciente', (await page.$$eval('#rspMain tr[data-rsp-pac]', (t) => t.length)) === 2);
  await page.fill('#rspQ', setup.n1.slice(0, 4));
  await page.waitForTimeout(400);
  check('busca por paciente', (await page.$$eval('#rspMain tr[data-rsp-pac]', (t) => t.length)) === 1);
  await page.fill('#rspQ', '');
  await page.waitForTimeout(400);
  await ev(`(function(){ var e = document.getElementById("rspSem"); e.value = "3"; e.dispatchEvent(new Event("change", {bubbles: true})); })()`);
  await page.waitForTimeout(300);
  check('filtro de semana', (await page.$$eval('#rspMain tr[data-rsp-pac]', (t) => t.length)) === 1);
  await page.click('.rsp-chip');
  check('etiqueta liga/desliga especialidade', (await page.$$('#rspMain tr[data-rsp-pac]')).length === 0);
  check('sem erros de JS', errors.length === 0, errors.join(' | '));
  await browser.close();
  fs.unlinkSync(evPage);
  console.log(fails ? 'FALHAS: ' + fails : 'ALL PASS');
  process.exit(fails ? 1 : 0);
})();
