// Planner → Outras Opções → Sugerir Agendamento: sugere pelas janelas/quadros e oferece remover sessões fora do horário e do quadro.
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
(async () => {
  const src = fs.readFileSync(path.join(__dirname, 'page.html'), 'utf8');
  const i = src.indexOf('"use strict";');
  const evPage = path.join(__dirname, 'page_sg.html');
  fs.writeFileSync(evPage, src.slice(0, i + 13) + '\nwindow.__ev = function(x){ return eval(x); };\n' + src.slice(i + 13));
  const browser = await chromium.launch(require('./launch-opts'));
  const page = await browser.newPage({ viewport: { width: 1400, height: 900 } });
  const errors = []; page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('file://' + evPage);
  await page.waitForSelector('#gridHost .book');
  const ev = (c) => page.evaluate((x) => window.__ev(x), c);
  let fails = 0;
  const check = (l, ok, x) => { console.log(l, !!ok, x === undefined ? '' : x); if (!ok) fails++; };
  await ev(`(async function(){
    var db = await window.claude.use('db');
    await db.doc('config/specialties').set({list: [{id: 'fono', name: 'Fonoaudiologia', sigla: 'FN'}]});
    await db.doc('config/professionals').set({list: [{id: 'f1', nome: 'Fono Um', name: 'Fono Um', specialtyId: 'fono'}]});
    await db.doc('config/rooms').set({list: [{id: 'rA', name: 'Fonoaudiologia', aba: false, color: 'teal', therapists: [{id: 'a1', name: 'Fono Um', professionalId: 'f1'}]}]});
    await db.doc('patients/all').set({list: [{id: 'pa', nome: 'Paciente A', idade: 8}]});
    var ids = []; ['seg','ter','qua','qui','sex'].forEach(function(d){ for (var w = 1; w <= 4; w++) ids.push(d + '-' + w); });
    for (var k = 0; k < ids.length; k++) await db.doc('schedule/' + ids[k]).set({bookings: {}});
    await db.doc('schedule/seg-1').set({bookings: {'07:20|rA|a1': {patient: 'Paciente A', note: ''}}});
  })()`);
  await page.waitForTimeout(600);
  // janela só na segunda; a sessão existente às 07:20 de segunda está dentro; uma de quarta (fora) será removível
  await ev(`(function(){ var h = {}; ['seg','ter','qua','qui','sex'].forEach(function(d){ h[d] = {ativo: d === 'seg', manha: {inicio: '07:20', fim: '12:00'}, tarde: {inicio: '', fim: ''}}; });
    state.treatments = [{id: 'ta', patientId: 'pa', inicio: '2026-01-01', status: 'ativo', tipo: 'novo', vencPor: 'sem', horarios: h, specHours: [{id: 'la', specId: 'fono', hours: 4, service: 'sessao', profId: 'f1', semanas: '', dia: 'seg'}]}]; rebuildPatients(); })()`);
  await ev(`(async function(){ var db = await window.claude.use('db'); await db.doc('schedule/qua-1').set({bookings: {'09:20|rA|a1': {patient: 'Paciente A', note: ''}}}); })()`);
  await page.waitForTimeout(500);
  await page.click('#plToolsBtn'); await page.waitForTimeout(150);
  check('Botão Sugerir Agendamento visível?', !(await page.$eval('#plSugBtn', (b) => b.hidden)));
  await page.$eval('#plSugBtn', (b) => b.click());
  await page.waitForSelector('#ovPlSg');
  await page.waitForTimeout(400);
  await page.$eval('#sgPat', (s) => { s.value = 'pa'; s.dispatchEvent(new Event('change', { bubbles: true })); });
  await page.waitForSelector('[data-sg-on]');
  const n = await page.$$eval('[data-sg-on]', (a) => a.length);
  check('Faltam 2 sessões (4 contratadas, 2 já marcadas) → 2 sugestões?', n === 2, n);
  const txt = await page.$$eval('[data-sg-sel]', (a) => a.map((s) => s.options[s.selectedIndex].text));
  check('Todas as sugestões em segunda (dia do quadro e janela)?', txt.every((t) => /^Segunda/.test(t)), JSON.stringify(txt));
  const rm = await page.$$eval('[data-sg-rm]', (a) => a.length);
  check('Sessão de quarta (fora da janela e do quadro) oferecida para remover?', rm === 1, rm);
  check('Remoção vem desmarcada?', await page.$eval('[data-sg-rm]', (c) => !c.checked));
  await page.$eval('[data-sg-rm]', (c) => c.click());
  await page.click('#sgApply');
  await page.waitForSelector('.confirm-overlay button.primary, .confirm-overlay .btn:not(.ghost)');
  await page.click('.confirm-overlay button.primary, .confirm-overlay .btn:not(.ghost)');
  await page.waitForTimeout(700);
  const seg = await ev(`JSON.stringify((window.__STORE__['schedule/seg-2'] || {}).bookings || {}) + JSON.stringify((window.__STORE__['schedule/seg-1'] || {}).bookings || {})`);
  const qua = await ev(`JSON.stringify((window.__STORE__['schedule/qua-1'] || {}).bookings || {})`);
  check('Sessões gravadas em segunda e a de quarta removida?', /Paciente A/.test(seg) && !/Paciente A/.test(qua), seg.slice(0, 120) + ' | ' + qua);
  check('no JS errors?', errors.length === 0, JSON.stringify(errors));
  fs.unlinkSync(evPage);
  await browser.close();
  process.exit(fails ? 1 : 0);
})();
